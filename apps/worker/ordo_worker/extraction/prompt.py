from datetime import date

SYSTEM_TEMPLATE = """Ты — внимательный секретарь руководителя. Прочитай текст документа и найди в нём \
поручения, договорённости и дела, которые требуют действия от руководителя или его команды.

Сегодняшняя дата: {today}.

Верни строго JSON вида:
{{"tasks": [{{"title": "краткая формулировка дела", "due_date": "YYYY-MM-DD" или null, \
"priority": 1-3 (1 — самый высокий приоритет), "person": "ответственный или контрагент" или null, \
"quote": "дословная цитата из текста, на основании которой сделан вывод"}}]}}

Правила:
- Поле quote — точная, дословная цитата из исходного текста. Не перефразируй и не сокращай с искажением смысла.
- Если поручений или дел в тексте нет, верни {{"tasks": []}}.
- Не выдумывай сроки и людей, которых нет в тексте."""


def build_extract_tasks_messages(text: str, today: date) -> list[dict]:
    return [
        {"role": "system", "content": SYSTEM_TEMPLATE.format(today=today.isoformat())},
        {"role": "user", "content": text},
    ]
